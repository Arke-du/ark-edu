ALIASES_COMPONENTES = {
    "portugues": "Língua Portuguesa",
    "lingua portuguesa": "Língua Portuguesa",
    "matematica": "Matemática",
}


def garantir_tabelas_matrizes(db_path: str) -> None:
    banco = sqlite3.connect(db_path)
    try:
        banco.execute("PRAGMA foreign_keys = ON")
        banco.executescript("""
        CREATE TABLE IF NOT EXISTS matrizes_avaliacao (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            sistema TEXT NOT NULL,
            ano INTEGER NOT NULL,
            tipo TEXT NOT NULL,
            nome TEXT NOT NULL,
            fonte TEXT,
            ativo INTEGER NOT NULL DEFAULT 1,
            UNIQUE(sistema, ano, tipo)
        );
        CREATE TABLE IF NOT EXISTS etapas_avaliadas (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            codigo TEXT NOT NULL UNIQUE,
            nome TEXT NOT NULL,
            ordem INTEGER NOT NULL
        );
        CREATE TABLE IF NOT EXISTS componentes_avaliados (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            codigo TEXT NOT NULL UNIQUE,
            nome TEXT NOT NULL
        );
        CREATE TABLE IF NOT EXISTS descritores_avaliacao (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            matriz_id INTEGER NOT NULL,
            etapa_id INTEGER NOT NULL,
            componente_id INTEGER NOT NULL,
            codigo TEXT NOT NULL,
            descricao TEXT NOT NULL,
            modalidade_item TEXT NOT NULL DEFAULT 'Objetiva',
            eixo TEXT,
            ativo INTEGER NOT NULL DEFAULT 1,
            FOREIGN KEY(matriz_id) REFERENCES matrizes_avaliacao(id),
            FOREIGN KEY(etapa_id) REFERENCES etapas_avaliadas(id),
            FOREIGN KEY(componente_id) REFERENCES componentes_avaliados(id),
            UNIQUE(matriz_id, etapa_id, componente_id, codigo, modalidade_item)
        );
        CREATE INDEX IF NOT EXISTS idx_descritores_contexto
            ON descritores_avaliacao(matriz_id, etapa_id, componente_id, ativo);
        """)

        for item in MATRIZES:
            banco.execute("""
                INSERT INTO matrizes_avaliacao (sistema, ano, tipo, nome, fonte, ativo)
                VALUES (?, ?, ?, ?, ?, ?)
                ON CONFLICT(sistema, ano, tipo) DO UPDATE SET
                    nome=excluded.nome, fonte=excluded.fonte, ativo=excluded.ativo
            """, (item["sistema"], item["ano"], item["tipo"], item["nome"], item["fonte"], item["ativo"]))

        for item in ETAPAS:
            banco.execute("""
                INSERT INTO etapas_avaliadas (codigo, nome, ordem)
                VALUES (?, ?, ?)
                ON CONFLICT(codigo) DO UPDATE SET nome=excluded.nome, ordem=excluded.ordem
            """, (item["codigo"], item["nome"], item["ordem"]))

        for item in COMPONENTES:
            banco.execute("""
                INSERT INTO componentes_avaliados (codigo, nome)
                VALUES (?, ?)
                ON CONFLICT(codigo) DO UPDATE SET nome=excluded.nome
            """, (item["codigo"], item["nome"]))

        matrizes_ids = {
            (r[1].upper(), r[2], r[3]): r[0]
            for r in banco.execute("SELECT id, sistema, ano, tipo FROM matrizes_avaliacao")
        }
        etapas_ids = {r[1]: r[0] for r in banco.execute("SELECT id, codigo FROM etapas_avaliadas")}
        componentes_ids = {r[1]: r[0] for r in banco.execute("SELECT id, codigo FROM componentes_avaliados")}
        matriz_original = {
            item["id"]: (item["sistema"].upper(), item["ano"], item["tipo"])
            for item in MATRIZES
        }
        etapa_original = {item["id"]: item["codigo"] for item in ETAPAS}
        componente_original = {item["id"]: item["codigo"] for item in COMPONENTES}

        for item in DESCRITORES:
            banco.execute("""
                INSERT INTO descritores_avaliacao (
                    matriz_id, etapa_id, componente_id, codigo, descricao,
                    modalidade_item, eixo, ativo
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?)
                ON CONFLICT(matriz_id, etapa_id, componente_id, codigo, modalidade_item)
                DO UPDATE SET
                    descricao=excluded.descricao,
                    eixo=excluded.eixo,
                    ativo=excluded.ativo
            """, (
                matrizes_ids[matriz_original[item["matriz_id"]]],
                etapas_ids[etapa_original[item["etapa_id"]]],
                componentes_ids[componente_original[item["componente_id"]]],
                item["codigo"],
                item["descricao"],
                item["modalidade_item"],
                item["eixo"],
                item["ativo"],
            ))

        banco.commit()
    finally:
        banco.close()


def _codigo_etapa(etapa: str, ano_serie: str) -> str:
    numero = "".join(c for c in str(ano_serie or "") if c.isdigit())
    etapa_normalizada = _normalizar(etapa)
    ano_normalizado = _normalizar(ano_serie)

    if etapa_normalizada == "ensino medio" or "serie" in ano_normalizado:
        return "EM03" if numero == "3" else ""

    return {"2": "EF02", "5": "EF05", "9": "EF09"}.get(numero, "")


def _codigo_componente(componente: str) -> str:
    nome = ALIASES_COMPONENTES.get(_normalizar(componente), componente)
    normalizado = _normalizar(nome)
    if normalizado == "lingua portuguesa":
        return "LP"
    if normalizado == "matematica":
        return "MAT"
    return ""


def consultar_matrizes(
    db_path: str,
    *,
    sistema: str,
    etapa: str,
    componente: str,
    ano_serie: str,
    matriz_id: int | None = None,
) -> dict[str, list[Any] | str | bool]:
    garantir_tabelas_matrizes(db_path)

    sistema = str(sistema or "").strip().upper()
    codigo_etapa = _codigo_etapa(etapa, ano_serie)
    codigo_componente = _codigo_componente(componente)

    sistemas_disponiveis = {"SAETO", "SAEB"}
    if sistema not in sistemas_disponiveis:
        return {
            "matrizes": [],
            "descritores": [],
            "disponivel": False,
            "mensagem": "Selecione SAETO ou SAEB."
        }

    if not codigo_etapa or not codigo_componente:
        if sistema == "SAEB":
            mensagem = (
                "O SAEB possui descritores codificados para Língua Portuguesa e Matemática "
                "no 5º e 9º anos do Ensino Fundamental e na 3ª série do Ensino Médio."
            )
        else:
            mensagem = (
                "O SAETO 2025 possui descritores para Língua Portuguesa e Matemática "
                "no 2º, 5º e 9º anos do Ensino Fundamental e na 3ª série do Ensino Médio."
            )
        return {
            "matrizes": [],
            "descritores": [],
            "disponivel": False,
            "mensagem": mensagem,
        }

    if sistema == "SAEB" and codigo_etapa == "EF02":
        return {
            "matrizes": [],
            "descritores": [],
            "disponivel": False,
            "mensagem": (
                "Esta base do SAEB não contém descritores D para o 2º ano. "
                "Selecione o 5º ano, o 9º ano ou a 3ª série do Ensino Médio."
            ),
        }

    banco = sqlite3.connect(db_path)
    banco.row_factory = sqlite3.Row
    try:
        matrizes = banco.execute("""
            SELECT DISTINCT m.id, m.sistema, m.ano, m.tipo, m.nome, m.fonte
            FROM matrizes_avaliacao m
            JOIN descritores_avaliacao d ON d.matriz_id = m.id AND d.ativo = 1
            JOIN etapas_avaliadas e ON e.id = d.etapa_id
            JOIN componentes_avaliados c ON c.id = d.componente_id
            WHERE m.ativo = 1
              AND UPPER(m.sistema) = ?
              AND e.codigo = ?
              AND c.codigo = ?
            ORDER BY m.ano DESC, m.nome COLLATE NOCASE
        """, (sistema, codigo_etapa, codigo_componente)).fetchall()

        matrizes_saida = [{
            "id": r["id"],
            "nome": r["nome"],
            "ano": r["ano"],
            "tipo": r["tipo"],
            "fonte": r["fonte"] or "",
            "valor": r["nome"],
        } for r in matrizes]

        if matriz_id is None and len(matrizes_saida) == 1:
            matriz_id = matrizes_saida[0]["id"]

        descritores_saida = []
        if matriz_id:
            linhas = banco.execute("""
                SELECT d.codigo, d.descricao, d.modalidade_item, d.eixo,
                       e.nome AS etapa, c.nome AS componente
                FROM descritores_avaliacao d
                JOIN matrizes_avaliacao m ON m.id = d.matriz_id
                JOIN etapas_avaliadas e ON e.id = d.etapa_id
                JOIN componentes_avaliados c ON c.id = d.componente_id
                WHERE d.ativo = 1
                  AND d.matriz_id = ?
                  AND UPPER(m.sistema) = ?
                  AND e.codigo = ?
                  AND c.codigo = ?
                ORDER BY
                    CASE
                        WHEN d.codigo GLOB 'D[0-9]*'
                        THEN CAST(SUBSTR(d.codigo, 2) AS INTEGER)
                        ELSE 999999
                    END,
                    d.codigo COLLATE NOCASE,
                    d.modalidade_item COLLATE NOCASE
            """, (matriz_id, sistema, codigo_etapa, codigo_componente)).fetchall()

            descritores_saida = [{
                "codigo": r["codigo"],
                "descricao": r["descricao"],
                "modalidade_item": r["modalidade_item"],
                "eixo": r["eixo"] or "",
                "valor": f"{r['codigo']} — {r['descricao']}",
                "texto": (
                    f"{r['codigo']} — {r['descricao']}"
                    + (f" · {r['eixo']}" if r["eixo"] else "")
                ),
            } for r in linhas]

        return {
            "matrizes": matrizes_saida,
            "descritores": descritores_saida,
            "disponivel": bool(matrizes_saida),
            "mensagem": (
                ""
                if matrizes_saida
                else f"Nenhuma matriz {sistema} foi encontrada para esta classificação."
            ),
        }
    finally:
        banco.close()